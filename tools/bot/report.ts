import type { RunOptions, RunResult, Sample } from './runner';

type Ring = 1 | 2 | 3 | 4;

interface ModelGoal {
  id: string;
  /** Model time (h) including its fixed content hours. */
  t: number;
  /** Model time without the content hours before the goal (pure earning time). */
  tNoContent: number;
  build: ShipBuild;
  ring: Ring;
  /** Total income after the goal (kr/h, incl. contracts, loot, exploration share). */
  inc: number;
}

function modelGoals(): Map<string, ModelGoal> {
  const r = run();
  const out = new Map<string, ModelGoal>();
  let content = 0;
  for (const e of r.log) {
    if (e.kind !== 'main' || !e.g.id) continue;
    const g = e.g as { id: string; fixedH?: number };
    if (g.fixedH) content += g.fixedH;
    out.set(g.id, { id: g.id, t: e.t, tNoContent: e.t - content, build: e.b!, ring: e.ring!, inc: (e as unknown as { inc: number }).inc });
  }
  return out;
}

const quantile = (xs: readonly number[], q: number): number => {
  if (xs.length === 0) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  const i = (s.length - 1) * q;
  const lo = Math.floor(i);
  const hi = Math.ceil(i);
  return s[lo]! + (s[hi]! - s[lo]!) * (i - lo);
};
const median = (xs: readonly number[]): number => quantile(xs, 0.5);

/** Minutes → "12.3 min" / "1:23 h"; Infinity → "not reached". */
function fmtT(min: number): string {
  if (!Number.isFinite(min)) return 'not reached';
  if (Number.isNaN(min)) return '–';
  if (min < 60) return `${min.toFixed(1)} min`;
  const h = Math.floor(min / 60);
  return `${h}:${String(Math.round(min - h * 60)).padStart(2, '0')} h`;
}
const k = (x: number): string => (!Number.isFinite(x) ? '–' : Math.abs(x) >= 1000 ? `${(x / 1000).toFixed(1)} k` : `${Math.round(x)}`);
const pct = (x: number): string => (Number.isFinite(x) ? `${Math.round(x * 100)} %` : '–');

/** Value of a sample series at time t (s) – linear between samples. */
function at(samples: readonly Sample[], t: number, key: 'minedValue' | 'earned' | 'credits' | 'rewards' | 'units'): number {
  if (samples.length === 0) return 0;
  if (t <= samples[0]!.t) return samples[0]![key];
  for (let i = 1; i < samples.length; i++) {
    const a = samples[i - 1]!;
    const b = samples[i]!;
    if (t <= b.t) return a[key] + ((b[key] - a[key]) * (t - a.t)) / Math.max(1e-9, b.t - a.t);
  }
  return samples[samples.length - 1]![key];
}

const MAIN_GOALS = BOT_GOALS.filter((g) => !g.botOnly).map((g) => g.id);
const EXTRA: { id: string; label: string; model: string | null }[] = [
  { id: 'firstSale', label: 'First sale', model: null },
  { id: 'firstTitanium', label: 'First titanium mined', model: 'tank' },
  { id: 'firstRing2', label: 'First flight into ring 2 (> 1500 u)', model: 'tank' },
  { id: 'firstContract', label: 'First contract turned in', model: null },
];

export async function buildReport(
  results: RunResult[],
  meta: { hours: number; options: Partial<RunOptions>; overrides?: string[] },
): Promise<string> {
  const N = results.length;
  const model = modelGoals();
  const lines: string[] = [];
  const p = (s = ''): void => {
    lines.push(s);
  };
  const opts = meta.options;
  const wall = results.reduce((s, r) => s + r.wallMs, 0) / 1000;

  p('# Balance bot report (headless play of the real simulation vs. the econ model)');
  p();
  p(`> Generated by \`npm run bot\` (tools/bot) – ${N} seeds (${results.map((r) => r.seed).join(', ')}) × ${meta.hours} game hours, ` +
    `normal difficulty (standard preset), dock dwell ${opts.dwellSeconds ?? 15} s, mining contracts ${opts.contracts === false ? 'off' : 'on'}, ` +
    `starting armor ${opts.firstDay === false ? 'off' : 'on'}, Guild Training ${opts.training === 'play' ? 'played first (scripted)' : 'skipped (starter ship)'}. Simulation time ${k(wall)} s CPU in total (${(wall / Math.max(1, N)).toFixed(1)} s per seed).`);
  if (meta.overrides?.length) p(`> **What-if run** – balance constants overridden in memory: ${meta.overrides.join(', ')}.`);
  p('> The model column is `econ-model.mjs` (ch. 3.5 B of the long-term design); "model w/o content" removes the fixed content hours');
  p('> (e.g. the 1 h of Echo-0/1 + First Day before "fill T1"), because the bot only mines, sells and refits.');
  p();

  // ------------------------------------------------------------------ milestones
  p('## 1. Milestones (game time)');
  p();
  p('| Milestone | Model | Model w/o content | Bot median | Bot p10 | Bot p90 | Reached | Bot / model (w/o content) |');
  p('|---|---|---|---|---|---|---|---|');
  const timesOf = (id: string): number[] => results.map((r) => (r.milestones[id] === undefined ? Infinity : r.milestones[id]! / 60));
  const row = (label: string, id: string, modelId: string | null): void => {
    const ts = timesOf(id);
    const reached = ts.filter(Number.isFinite).length;
    const m = modelId ? model.get(modelId) : undefined;
    const med = median(ts);
    const ratio = m && Number.isFinite(med) ? med / (m.tNoContent * 60) : NaN;
    p(`| ${label} | ${m ? fmtT(m.t * 60) : '–'} | ${m ? fmtT(m.tNoContent * 60) : '–'} | ${fmtT(med)} | ${fmtT(quantile(ts, 0.1))} | ${fmtT(quantile(ts, 0.9))} | ${reached}/${N} | ${Number.isFinite(ratio) ? `${ratio.toFixed(2)}×` : '–'} |`);
  };
  for (const g of personaGoals(opts.persona)) row(`${g.label}${g.botOnly ? ' (bot only)' : ''} \`${g.id}\``, g.id, g.botOnly ? null : g.id);
  for (const e of EXTRA) row(`${e.label} \`${e.id}\``, e.id, e.model);
  p();
  p('Unreached milestones count as "not reached" (= later than the run) in the quantiles.');
  p();

  // ------------------------------------------------------------------ income per stage
  p('## 2. Income per stage');
  p();
  p('Bot income = value of the mined rock at home sell prices (units × base × ring-1 multiplier × 0.8), measured between two');
  p('consecutive milestones; "gross" adds contract and First Day rewards. Model "mining" = `income(build, ring).mining`');
  p('(trip model × 0.75 human efficiency × (1 − op. cost)); model "total" adds contracts, loot, salvage and the exploration share.');
  p();
  p('| Stage (after …) | Bot mining kr/h (median) | p10 – p90 | Bot gross kr/h | Model mining kr/h | Model total kr/h | Bot / model mining | Runs |');
  p('|---|---|---|---|---|---|---|---|');
  const stageIds = ['start', ...MAIN_GOALS];
  for (let i = 0; i < stageIds.length; i++) {
    const id = stageIds[i]!;
    const rates: number[] = [];
    const gross: number[] = [];
    for (const r of results) {
      const t1 = id === 'start' ? 0 : r.milestones[id];
      if (t1 === undefined) continue;
      let t2 = r.hours * 3600;
      for (const next of stageIds.slice(i + 1)) if (r.milestones[next] !== undefined && r.milestones[next]! > t1) t2 = Math.min(t2, r.milestones[next]!);
      if (t2 - t1 < 180) continue;
      const h = (t2 - t1) / 3600;
      rates.push((at(r.samples, t2, 'minedValue') - at(r.samples, t1, 'minedValue')) / h);
      gross.push((at(r.samples, t2, 'minedValue') - at(r.samples, t1, 'minedValue') + at(r.samples, t2, 'rewards') - at(r.samples, t1, 'rewards')) / h);
    }
    const m = id === 'start' ? null : model.get(id);
    const build: ShipBuild = m?.build ?? { cockpit: 1, lasers: 1, laserTier: 1, holds: 2, holdTier: 1 };
    const ring: Ring = m?.ring ?? 1;
    const inc = income(build, ring);
    const label = id === 'start' ? 'start (starter ship)' : `\`${id}\``;
    const med = median(rates);
    p(`| ${label} | ${k(med)} | ${k(quantile(rates, 0.1))} – ${k(quantile(rates, 0.9))} | ${k(median(gross))} | ${k(inc.mining)} | ${k(inc.total)} | ${Number.isFinite(med) ? `${(med / inc.mining).toFixed(1)}×` : '–'} | ${rates.length} |`);
  }
  p();
  p('Stages shorter than 3 minutes are skipped (two refits in one docking).');
  p();
  p('**Why the income differs** – the same stages split into throughput (units mined per hour, docking and travel included)');
  p('and value per unit. The model throughput is shown as is and divided by its human efficiency (`HUMAN_EFF` = ' + MODEL.HUMAN_EFF + ')');
  p('because the bot plays without idle time; the model value per unit is the ring mix at local prices (`avgPrice(ring)`).');
  p();
  p('| Stage (after …) | Bot u/h | Model u/h | Model u/h ÷ HUMAN_EFF | Bot kr/u | Model kr/u | Throughput ratio (bot ÷ perfect model) | Value ratio |');
  p('|---|---|---|---|---|---|---|---|');
  for (let i = 1; i < stageIds.length; i++) {
    const id = stageIds[i]!;
    const uph: number[] = [];
    const kpu: number[] = [];
    for (const r of results) {
      const t1 = r.milestones[id];
      if (t1 === undefined) continue;
      let t2 = r.hours * 3600;
      for (const next of stageIds.slice(i + 1)) if (r.milestones[next] !== undefined && r.milestones[next]! > t1) t2 = Math.min(t2, r.milestones[next]!);
      if (t2 - t1 < 180) continue;
      const du = at(r.samples, t2, 'units') - at(r.samples, t1, 'units');
      uph.push(du / ((t2 - t1) / 3600));
      if (du > 0) kpu.push((at(r.samples, t2, 'minedValue') - at(r.samples, t1, 'minedValue')) / du);
    }
    const m = model.get(id);
    if (!m || !uph.length) continue;
    const tr = trip(m.build, m.ring);
    const mu = ((tr.cargo * 3600) / tr.secs) * MODEL.HUMAN_EFF;
    const mk = avgPrice(m.ring);
    p(`| \`${id}\` (P${m.ring}) | ${k(median(uph))} | ${k(mu)} | ${k(mu / MODEL.HUMAN_EFF)} | ${median(kpu).toFixed(1)} | ${mk.toFixed(1)} | ${(median(uph) / (mu / MODEL.HUMAN_EFF)).toFixed(1)}× | ${(median(kpu) / mk).toFixed(1)}× |`);
  }
  p();
  p('**Income per game hour** (mined value, median over seeds):');
  p();
  p('| Hour | Bot mined value kr | Bot credits at end of hour | Bot units mined |');
  p('|---|---|---|---|');
  for (let h = 1; h <= Math.ceil(meta.hours); h++) {
    const t1 = (h - 1) * 3600;
    const t2 = Math.min(h, meta.hours) * 3600;
    const v = results.map((r) => at(r.samples, t2, 'minedValue') - at(r.samples, t1, 'minedValue'));
    const c = results.map((r) => at(r.samples, t2, 'credits'));
    const u = results.map((r) => at(r.samples, t2, 'units') - at(r.samples, t1, 'units'));
    p(`| ${h} | ${k(median(v))} | ${k(median(c))} | ${k(median(u))} |`);
  }
  p();

  // ------------------------------------------------------------------ credit curve
  p('## 3. Credit curve (median over seeds)');
  p();
  p('| Game time | Credits | Mined value (cumulative) | Rewards (cumulative) |');
  p('|---|---|---|---|');
  const step = meta.hours > 1.5 ? 10 : 5;
  for (let m = step; m <= meta.hours * 60 + 1e-9; m += step) {
    const t = m * 60;
    p(`| ${fmtT(m)} | ${k(median(results.map((r) => at(r.samples, t, 'credits'))))} | ${k(median(results.map((r) => at(r.samples, t, 'minedValue'))))} | ${k(median(results.map((r) => at(r.samples, t, 'rewards'))))} |`);
  }
  p();

  // ------------------------------------------------------------------ trips
  p('## 4. Trip anatomy (bot) vs. the trip model');
  p();
  const tripRows = (label: string, ring2: boolean): void => {
    const trips = results.flatMap((r) => r.trips.filter((t) => t.ring2 === ring2 && t.units > 1));
    if (!trips.length) return;
    const dur = trips.map((t) => t.end - t.start);
    const units = trips.map((t) => t.units);
    const mining = trips.map((t) => t.miningSeconds);
    const transit = trips.map((t) => t.transitSeconds);
    const site = trips.map((t) => Math.max(0, t.end - t.start - t.transitSeconds - t.miningSeconds));
    const vein = trips.reduce((s, t) => s + t.veinSeconds, 0) / Math.max(1e-9, trips.reduce((s, t) => s + t.miningSeconds, 0));
    const rate = trips.map((t) => t.units / Math.max(1, t.miningSeconds));
    const fuel = trips.map((t) => t.fuelUsed);
    const value = trips.map((t) => t.value);
    p(`| ${label} | ${trips.length} | ${median(dur).toFixed(0)} s | ${median(units).toFixed(0)} | ${k(median(value))} | ${median(mining).toFixed(0)} s | ${median(transit).toFixed(0)} s | ${median(site).toFixed(0)} s | ${pct(vein)} | ${median(rate).toFixed(2)} u/s | ${median(fuel).toFixed(0)} |`);
  };
  p('| Trips | Count | Undock→dock | Units | Value kr | Beam on rock | Transit (to first / from last rock) | Between rocks | Beam on vein | Units per beam-second | Fuel |');
  p('|---|---|---|---|---|---|---|---|---|---|---|');
  tripRows('ring 1 phase', false);
  tripRows('ring 2 phase (titanium)', true);
  p();
  const dockSec = results.reduce((s, r) => s + r.docked.seconds, 0) / Math.max(1, results.reduce((s, r) => s + r.docked.count, 0));
  p(`Average time docked per visit (dwell + 1 s docking animation): ${dockSec.toFixed(0)} s.`);
  p();
  const b0: ShipBuild = { cockpit: 1, lasers: 1, laserTier: 1, holds: 2, holdTier: 1 };
  const b2 = model.get('laser2')?.build ?? b0;
  const t1 = trip(b0, 1);
  const t2 = trip(b2, 2);
  const rate = (b: ShipBuild, ring: Ring): number => b.lasers * MODEL.LASER_RATE[b.laserTier as Ring] * MODEL.VEIN * MODEL.RING[ring].search;
  p('Trip model for comparison (econ-model `trip()`):');
  p();
  p('| Model trip | Cargo | Total | Travel | Mining (cargo ÷ rate) | Dock overhead | Effective rate | Hazard × |');
  p('|---|---|---|---|---|---|---|---|');
  p(`| P1, starter ship | ${t1.cargo} | ${t1.secs.toFixed(0)} s | ${MODEL.RING[1].travel} s | ${(t1.cargo / rate(b0, 1)).toFixed(0)} s | ${MODEL.OVERHEAD} s | ${rate(b0, 1).toFixed(2)} u/s (lasers × rate × vein ${MODEL.VEIN} × search ${MODEL.RING[1].search}) | ${MODEL.RING[1].hazard} |`);
  p(`| P2, 2 lasers | ${t2.cargo} | ${t2.secs.toFixed(0)} s | ${MODEL.RING[2].travel} s | ${(t2.cargo / rate(b2, 2)).toFixed(0)} s | ${MODEL.OVERHEAD} s | ${rate(b2, 2).toFixed(2)} u/s (search ${MODEL.RING[2].search}) | ${MODEL.RING[2].hazard} |`);
  p();

  // ------------------------------------------------------------------ mix
  p('## 5. Mined mix and where the money comes from');
  p();
  const minedTot = {} as Record<ResourceId, number>;
  for (const r of RESOURCE_IDS) minedTot[r] = results.reduce((s, x) => s + x.mined[r], 0);
  const totalUnits = RESOURCE_IDS.reduce((s, r) => s + minedTot[r], 0);
  const totalValue = RESOURCE_IDS.reduce((s, r) => s + minedTot[r] * homeSellPrice(r), 0);
  p('| Resource | Share of units | Share of value | Home sell price | Model mix P1 | Model mix P2 |');
  p('|---|---|---|---|---|---|');
  const MIXKEY: Record<ResourceId, string> = { iron: 'fe', copper: 'cu', ice: 'ice', titanium: 'ti' };
  for (const r of RESOURCE_IDS) {
    const mk = MIXKEY[r] as keyof (typeof MODEL.MIX)[1];
    p(`| ${r} | ${pct(minedTot[r] / totalUnits)} | ${pct((minedTot[r] * homeSellPrice(r)) / totalValue)} | ${homeSellPrice(r).toFixed(1)} | ${pct(MODEL.MIX[1][mk] ?? 0)} | ${pct(MODEL.MIX[2][mk] ?? 0)} |`);
  }
  p();
  const reasons = new Map<string, number>();
  for (const r of results) for (const [key, v] of Object.entries(r.creditsByReason)) reasons.set(key, (reasons.get(key) ?? 0) + v / N);
  p(`Credit flows per run (mean): ${[...reasons].sort((a, b) => b[1] - a[1]).map(([key, v]) => `${key} ${k(v)}`).join(' · ')}.`);
  p();
  const fuelModes = new Map<string, number>();
  const secModes = new Map<string, number>();
  for (const r of results) {
    for (const [m, v] of Object.entries(r.fuelByMode)) fuelModes.set(m, (fuelModes.get(m) ?? 0) + v / N);
    for (const [m, v] of Object.entries(r.secondsByMode)) secModes.set(m, (secModes.get(m) ?? 0) + v / N);
  }
  p(`Time per pilot mode (mean per run): ${[...secModes].sort((a, b) => b[1] - a[1]).map(([m, v]) => `${m} ${fmtT(v / 60)}`).join(' · ')}.`);
  p(`Fuel per pilot mode (mean per run): ${[...fuelModes].sort((a, b) => b[1] - a[1]).map(([m, v]) => `${m} ${v.toFixed(0)}`).join(' · ')}.`);
  p();

  // ------------------------------------------------------------------ robustness
  p('## 6. Robustness: deaths, tows, stuck states, failures');
  p();
  const sum = (f: (r: RunResult) => number): number => results.reduce((s, r) => s + f(r), 0);
  p('| Event | Total over all runs | Runs affected |');
  p('|---|---|---|');
  const evRow = (label: string, f: (r: RunResult) => number): void => p(`| ${label} | ${k(sum(f))} | ${results.filter((r) => f(r) > 0).length}/${N} |`);
  evRow('Deaths', (r) => r.deaths.length);
  evRow('Tows (out of fuel)', (r) => r.counts.towed ?? 0);
  evRow('Stuck (no progress for the stuck limit)', (r) => r.stuck.length);
  evRow('Fled from pirates', (r) => r.counts.flee ?? 0);
  evRow('Approach timeouts (90 s, rock blacklisted)', (r) => r.counts.approachTimeout ?? 0);
  evRow('Mining without yield for 8 s (rock blacklisted)', (r) => r.counts.noYield ?? 0);
  evRow('Escape manoeuvres (4 s without nav progress)', (r) => r.counts.escape ?? 0);
  evRow('… of them energy-pumping escapes in open space (gravity wells, long stalls)', (r) => r.counts.pumpEscape ?? 0);
  evRow('Ram damage (HP)', (r) => r.counts.ramDamage ?? 0);
  evRow('Docking rejected (too far / too fast)', (r) => Object.entries(r.counts).filter(([key]) => key.startsWith('dockRejected')).reduce((s, [, v]) => s + v, 0));
  evRow('Goals skipped / partially built (hull budget)', (r) => (r.counts.goalSkipped ?? 0) + (r.counts.goalPartial ?? 0));
  evRow('Failed station actions', (r) => Object.values(r.failures).reduce((s, v) => s + v, 0));
  p();
  const failures = new Map<string, number>();
  for (const r of results) for (const [key, v] of Object.entries(r.failures)) failures.set(key, (failures.get(key) ?? 0) + v);
  if (failures.size) p(`Failed actions by reason: ${[...failures].map(([key, v]) => `${key} ×${v}`).join(', ')}.`);
  const stuck = results.flatMap((r) => r.stuck);
  if (stuck.length) {
    p();
    p('**Stuck states** (reproduce with `npm run bot -- --seeds=<seed> --hours=<h> --verbose`; tick = 1/60 s):');
    p();
    for (const s of stuck.slice(0, 30)) p(`- seed ${s.seed}, tick ${s.tick} (${fmtT(s.tick / 3600)}): ${s.kind} – ${s.detail}`);
  } else {
    p();
    p('No stuck states (no progress for the stuck limit) in any run.');
  }
  const deaths = results.flatMap((r) => r.deaths.map((d) => ({ seed: r.seed, ...d })));
  if (deaths.length) {
    p();
    p(`Deaths: ${deaths.map((d) => `seed ${d.seed} at ${fmtT(d.t / 60)} ${d.pos}`).join('; ')}.`);
  }
  const noteKinds = ['noYield', 'approachTimeout', 'outOfFuel', 'towed', 'flee', 'commitBlocked', 'commitFailed', 'craftFailed', 'goalSkipped'];
  const notes = results.flatMap((r) => r.notes.filter((n) => noteKinds.includes(n.kind)).map((n) => ({ seed: r.seed, ...n })));
  if (notes.length) {
    p();
    p('<details><summary>Event log samples (seed, tick, detail)</summary>');
    p();
    for (const n of notes.slice(0, 60)) p(`- seed ${n.seed}, tick ${n.tick}: ${n.kind} – ${n.detail}`);
    p();
    p('</details>');
  }
  p();

  // ------------------------------------------------------------------ M4b
  p('## 6b. M4b "World Comes Alive": world sites and events met by the bot');
  p();
  p('The pilot takes a cheap detour in ring 2 to a known derelict without sentries (relays → berth → terminal) or to a graveyard');
  p("(the first wreck analysis from outside the field) – `tools/bot/sites.ts`; it pulses the scanner every 2 min in ring 2. It never");
  p('chases comets, never cuts graveyard wrecks and flees ambushes like any pirates. Totals over all runs (P2 = while on ring-2 trips).');
  p();
  const m4 = (key: string): number => sum((r) => r.m4b?.[key] ?? 0);
  p('| Counter | All | P2 | Runs |');
  p('|---|---|---|---|');
  const m4row = (label: string, key: string): void => p(`| ${label} | ${k(m4(key))} | ${k(m4(`p2:${key}`))} | ${results.filter((r) => (r.m4b?.[key] ?? 0) > 0).length}/${N} |`);
  m4row('Ambush events (`eventStarted`)', 'event:ambush');
  for (const sec of ['quiet', 'guarded', 'contested', 'pirate']) m4row(`… spawned in a ${sec} sector${sec === 'quiet' || sec === 'guarded' ? ' (must be 0)' : ''}`, `ambush:${sec}`);
  m4row('Ambush pirates spawned', 'ambushPirates');
  m4row('… Gunner-led parties', 'ambushGunnerLed');
  m4row('Micrometeor showers', 'event:micrometeors');
  m4row('Micrometeor hits', 'micrometeorHits');
  m4row('… absorbed by the shield', 'micrometeorShielded');
  m4row('… HP of damage to parts', 'micrometeorDamage');
  m4row('Mines armed', 'minesArmed');
  m4row('… exploded', 'minesExploded');
  m4row('Graveyard sleepers woke', 'sleepersWoke');
  m4row('Relays powered', 'relaysPowered');
  m4row('Derelict berths', 'berths');
  m4row('Derelict Data (first berths)', 'derelictData');
  m4row('Derelict items: stash parts', 'derelictTaken:part');
  m4row('… plan fragments', 'derelictTaken:fragments');
  m4row('… fabricated parts', 'derelictTaken:crafted');
  m4row('… value of the parts (kr, part value)', 'derelictItemValue');
  m4row('Graveyard Data (first analysed wreck)', 'graveyardData');
  m4row('Comets sighted', 'cometsSighted');
  p();
  const met = ['ambush', 'sleeper', 'sentry', 'gunner'].map((x) => `${x} ${k(sum((r) => r.counts[`met:${x}`] ?? 0))}`).join(' · ');
  p(`Enemies met (distinct ids): ${met}. Site visits started: derelict ${k(sum((r) => r.counts['siteVisit:derelict'] ?? 0))}, graveyard ${k(sum((r) => r.counts['siteVisit:graveyard'] ?? 0))}; failed ${k(sum((r) => r.counts.siteVisitFailed ?? 0))}.`);
  // Data and the share of the M4b sources in ring 2
  const p2 = results.map((r) => {
    let t = 0;
    let earned = 0;
    let data = 0;
    for (let i = 1; i < r.samples.length; i++) {
      const a = r.samples[i - 1]!;
      const b = r.samples[i]!;
      if (!a.ring2) continue;
      t += b.t - a.t;
      earned += b.earned - a.earned;
      data += (b.data ?? 0) - (a.data ?? 0);
    }
    const h = t / 3600;
    const m4bData = (r.m4b?.['p2:derelictData'] ?? 0) + (r.m4b?.['p2:graveyardData'] ?? 0);
    return { h, earned, data, m4bData, items: r.m4b?.['p2:derelictItemValue'] ?? 0 };
  });
  const tot = p2.reduce((s, x) => ({ h: s.h + x.h, earned: s.earned + x.earned, data: s.data + x.data, m4bData: s.m4bData + x.m4bData, items: s.items + x.items }), { h: 0, earned: 0, data: 0, m4bData: 0, items: 0 });
  const bySource = new Map<string, number>();
  for (const r of results) for (const [src, v] of Object.entries(r.dataBySource ?? {})) bySource.set(src, (bySource.get(src) ?? 0) + v);
  p();
  p(`Ring 2 over all runs: ${tot.h.toFixed(1)} h, earned ${k(tot.earned / Math.max(1e-9, tot.h))} kr/h, Data ${(tot.data / Math.max(1e-9, tot.h)).toFixed(1)} D/h ` +
    `(of it derelicts and graveyards ${(tot.m4bData / Math.max(1e-9, tot.h)).toFixed(1)} D/h); terminal parts worth ${k(tot.items / Math.max(1e-9, tot.h))} kr/h of part value ` +
    `(${pct(tot.items / Math.max(1e-9, tot.earned))} of the P2 earnings). Data by source (all runs): ${[...bySource].map(([s, v]) => `${s} ${k(v)}`).join(' · ') || '–'}.`);
  p();

  // ------------------------------------------------------------------ M4c
  const m4c = (key: string): number => sum((r) => r.m4c?.[key] ?? 0);
  if (results.some((r) => Object.keys(r.m4c ?? {}).length > 0)) {
    p('## 6c. M4c on-board workshop (refinery, repair module)');
    p();
    p(`Persona \`${opts.persona ?? 'standard'}\` – totals over all runs (the refined bonus is estimated from the refined units sold × the station's sell price × the bonus paid there: ${REFINED_BONUS} under the W1 refined price ceiling, less for ring 3–4 iron / copper).`);
    p();
    p('| Counter | All runs | Per run |');
    p('|---|---|---|');
    const wrow = (label: string, key: string): void => p(`| ${label} | ${k(m4c(key))} | ${k(m4c(key) / N)} |`);
    wrow('Ore refined in flight (u)', 'refined');
    wrow('Refined units sold', 'refinedSold');
    wrow('≈ refined bonus (kr)', 'refinedBonus');
    wrow('Refinery seconds topping up fuel from ice', 'refiningSeconds:fuel');
    wrow('Refinery seconds refining ore', 'refiningSeconds:ore');
    wrow('HP repaired by repair modules', 'repairHp');
    wrow('… material drawn (Fe / Ti units)', 'repairMaterial');
    wrow('Parts brought back to full HP (`partRepaired`)', 'partsRepaired');
    wrow('Large-reactor blasts (`partBlast`)', 'partBlasts');
    const idle = Object.keys(results.reduce((o, r) => ({ ...o, ...(r.m4c ?? {}) }), {} as Record<string, number>)).filter((x) => x.startsWith('workshopIdle:'));
    for (const key of idle.sort()) wrow(`\`${key}\` events`, key);
    p();
  }

  // ------------------------------------------------------------------ M4d
  const m4d = (key: string): number => sum((r) => r.m4d?.[key] ?? 0);
  if (results.some((r) => Object.keys(r.m4d ?? {}).length > 0)) {
    const aiMax = Math.max(...results.map((r) => r.m4d?.aiShipsMax ?? 0));
    p('## 6d. M4d "Guild and Trade": Guild Watch, convoys and the AI budget');
    p();
    p(`Persona \`${opts.persona ?? 'standard'}\`${(opts.secured ?? []).length ? `, lanes secured from the start: ${(opts.secured ?? []).join(', ')}` : ''} – totals over all runs. ` +
      `The AI budget (pirates + live Guild Watch + escort convoy ships) peaked at **${aiMax}** (limit 10${aiMax > 10 ? ' – **exceeded**' : ''}).`);
    p();
    p('| Counter | All runs | Per run |');
    p('|---|---|---|');
    const drow = (label: string, key: string, fmt: (x: number) => string = k): void => p(`| ${label} | ${fmt(m4d(key))} | ${fmt(m4d(key) / N)} |`);
    drow('Most AI ships at once (max of the runs)', 'aiShipsMax', () => `${aiMax}`);
    drow('Distinct live Guild Watch ships met', 'watchMet');
    drow('Minutes with a live Watch ship near', 'watchSeconds', (x) => (x / 60).toFixed(1));
    drow('Watch engagements (`watchEngaged`)', 'watchEngaged');
    drow('Pirates destroyed by the Watch (no cargo loot, not a kill of the bot)', 'watchKills');
    drow('Watch ships lost', 'watchLost');
    drow('Convoy flyby warnings', 'convoyFlybys');
    drow('Seconds touching a convoy ship (sampled every 0.5 s)', 'convoyContactSeconds', (x) => x.toFixed(1));
    drow('Lanes secured at the start', 'securedLanes');
    p();
  }

  // ------------------------------------------------------------------ final ships
  p('## 7. Ships at the end of the runs');
  p();
  p('| Seed | Credits | Hull pts | Goals done | Parts |');
  p('|---|---|---|---|---|');
  for (const r of results) {
    const done = MAIN_GOALS.filter((id) => r.milestones[id] !== undefined).length;
    p(`| ${r.seed} | ${k(r.final.credits)} | ${r.final.hull} | ${done}/${MAIN_GOALS.length} | ${Object.entries(r.final.parts).map(([key, n]) => `${key}×${n}`).join(' ')} |`);
  }
  p();

  // ------------------------------------------------------------------ analysis
  // static hand-written analysis of the default run (left out of what-if runs)
  if (!meta.overrides?.length) {
    p(ANALYSIS.trim());
    p();
  }
  return lines.join('\n');
}
