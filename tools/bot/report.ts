// Markdown report of the balance bot: milestones (median / p10 / p90 over seeds) against the econ
// model (tools/econ/econ-model.mjs, ch. 3.5 of the long-term design), income per stage, trip
// anatomy, mined mix, robustness (deaths, tows, stuck states with seed + tick) and the hand-written
// analysis from tools/bot/analysis.ts.
import { avgPrice, income, MODEL, run, trip, type ShipBuild } from '../econ/econ-model.mjs';
import { RESOURCE_IDS, type ResourceId } from '../../src/data/resources';
import { BOT_GOALS } from './goals';
import { personaGoals } from './shipPlan';
import { REFINED_BONUS } from '../../src/data/workshop';
